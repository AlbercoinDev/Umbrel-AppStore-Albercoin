def select_language(header: str | None, query: str | None = None, cookie: str | None = None) -> str:
    if query in ("es", "en"):
        return query
    if cookie in ("es", "en"):
        return cookie
    for part in (header or "").split(","):
        code = part.split(";", 1)[0].strip().lower()
        if code.startswith("es"):
            return "es"
        if code.startswith("en"):
            return "en"
    return "es"


def t(lang: str, key: str, **values: object) -> str:
    table = TEXTS.get(lang, TEXTS["es"])
    text = table.get(key, TEXTS["es"].get(key, key))
    if values:
        try:
            return text.format(**values)
        except (KeyError, ValueError):
            return text
    return text


